import { mkdir, writeFile } from 'node:fs/promises';
import StyleDictionary from 'style-dictionary';
import { register } from '@tokens-studio/sd-transforms';

register(StyleDictionary);

const PREFIX = 'ipe';
const OUT_CSS = 'src/styles/generated';
const OUT_TS = 'src/tokens/generated';

const pureRef = /^\{([^}]+)\}$/;
const refToVar = (path) => `var(--${PREFIX}-${path.replace(/\./g, '-')})`;

async function loadTheme(theme) {
  const sd = new StyleDictionary({
    log: { verbosity: 'silent', warnings: 'disabled' },
    include: ['tokens/core.json'],
    source: [`tokens/${theme}.json`],
    preprocessors: ['tokens-studio'],
    platforms: {
      css: {
        transformGroup: 'tokens-studio',
        transforms: ['name/kebab'],
        prefix: PREFIX,
      },
    },
  });
  const { allTokens } = await sd.getPlatformTokens('css');
  return allTokens;
}

function cssValue(token) {
  const original = token.original.$value ?? token.original.value;
  if (typeof original === 'string') {
    const match = original.match(pureRef);
    if (match) return refToVar(match[1]);
  }
  return token.$value ?? token.value;
}

const isFrom = (token, file) => token.filePath.endsWith(file);
const declarations = (tokens) => tokens.map((t) => `  --${t.name}: ${cssValue(t)};`).join('\n');

const light = await loadTheme('light');
const dark = await loadTheme('dark');

const core = light.filter((t) => isFrom(t, 'core.json'));
const lightSemantic = light.filter((t) => isFrom(t, 'light.json'));
const darkSemantic = dark.filter((t) => isFrom(t, 'dark.json'));

const banner = '/* Generated by scripts/build-tokens.mjs from /tokens. Do not edit by hand. */';

const tokensCss = `${banner}

:root {
${declarations(core)}
}

:root,
[data-theme='light'] {
  color-scheme: light;
${declarations(lightSemantic)}
}

[data-theme='dark'] {
  color-scheme: dark;
${declarations(darkSemantic)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${declarations(darkSemantic).replace(/^ {2}/gm, '    ')}
  }
}
`;

const twName = (t) => t.name.replace(`${PREFIX}-`, '');
const tailwindCss = `${banner}
/* Usage: @import "tailwindcss"; @import "@rayssarrsilva/ipe/tokens.css"; @import "@rayssarrsilva/ipe/tailwind.css"; */

@theme inline {
${lightSemantic
  .filter((t) => t.type === 'color')
  .map(
    (t) =>
      `  --color-${twName(t).replace(/^(bg|text|border|action|feedback)-/, '$1-')}: var(--${t.name});`,
  )
  .join('\n')}
${core
  .filter((t) => t.path[0] === 'radius')
  .map((t) => `  --radius-${t.path[1]}: var(--${t.name});`)
  .join('\n')}
${core
  .filter((t) => t.path[0] === 'shadow')
  .map((t) => `  --shadow-${t.path[1]}: var(--${t.name});`)
  .join('\n')}
  --font-display: var(--${PREFIX}-font-families-display), Georgia, serif;
  --font-body: var(--${PREFIX}-font-families-body), system-ui, sans-serif;
}
`;

const toMeta = (t) => ({
  name: t.path.join('.'),
  cssVar: `--${t.name}`,
  type: t.type,
  value: t.$value ?? t.value,
  description: t.description ?? t.comment ?? '',
});

const tokensTs = `// Generated by scripts/build-tokens.mjs from /tokens. Do not edit by hand.

export interface TokenMeta {
  name: string;
  cssVar: string;
  type: string;
  value: unknown;
  description: string;
}

export const coreTokens: TokenMeta[] = ${JSON.stringify(core.map(toMeta), null, 2)};

export const lightTokens: TokenMeta[] = ${JSON.stringify(lightSemantic.map(toMeta), null, 2)};

export const darkTokens: TokenMeta[] = ${JSON.stringify(darkSemantic.map(toMeta), null, 2)};
`;

await mkdir(OUT_CSS, { recursive: true });
await mkdir(OUT_TS, { recursive: true });
await writeFile(`${OUT_CSS}/tokens.css`, tokensCss);
await writeFile(`${OUT_CSS}/tailwind.css`, tailwindCss);
await writeFile(`${OUT_TS}/tokens.ts`, tokensTs);

console.log(
  `tokens: ${core.length} core, ${lightSemantic.length} light, ${darkSemantic.length} dark`,
);
